let KSA = KSA_FALLBACK;
(async () => {
  try {
    const base = "https://cdn.jsdelivr.net/gh/homaily/Saudi-Arabia-Regions-Cities-and-Districts@master/json/";
    const [regs, cits] = await Promise.all([
      fetch(base + "regions_lite.json").then(r => r.json()),
      fetch(base + "cities_lite.json").then(r => r.json())
    ]);
    const byReg = {};
    cits.forEach(c => (byReg[c.region_id] ||= []).push(c.name_ar));
    const fix = { "الاحساء": "الأحساء", "ابها": "أبها" };
    KSA = regs.sort((a, b) => a.region_id - b.region_id).map(r => [
      r.name_ar,
      [...new Set((byReg[r.region_id] || []).map(n => fix[n] || n))].sort((a, b) => a.localeCompare(b, "ar"))
    ]);
    document.dispatchEvent(new Event("ksa-ready"));
  } catch { /* تبقى القائمة الاحتياطية */ }
})();
